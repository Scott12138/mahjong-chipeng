// ------------------------------------------------------------
//  颜色派生工具
// ------------------------------------------------------------

/** 与白混合：k=0 原色，k=1 纯白 */
export function tint(hex: string, k: number): string {
    const n = parseInt(hex.slice(1), 16);
    const r = (n >> 16) & 255;
    const g = (n >> 8) & 255;
    const b = n & 255;
    const mix = (v: number) => Math.round(v + (255 - v) * k);
    return '#' + [mix(r), mix(g), mix(b)].map((v) => v.toString(16).padStart(2, '0')).join('');
}

/** 压暗：k=0 原色，k=1 全黑 */
export function deep(hex: string, k: number): string {
    const n = parseInt(hex.slice(1), 16);
    const r = (n >> 16) & 255;
    const g = (n >> 8) & 255;
    const b = n & 255;
    const mix = (v: number) => Math.round(v * (1 - k));
    return '#' + [mix(r), mix(g), mix(b)].map((v) => v.toString(16).padStart(2, '0')).join('');
}

