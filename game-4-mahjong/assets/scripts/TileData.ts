/** 三族 */
export type Family = 'wan' | 'sou' | 'ton';
export const FAMILIES: Family[] = ['wan', 'sou', 'ton'];

/** 牌面标识：族 + 点数 1..9 */
export type PatternKey = string;   // 形如 'wan-1' / 'ton-9'

export function patternKey(fam: Family, num: number): PatternKey {
    return `${fam}-${num}`;
}

/** 反解牌面标识 */
export function parsePattern(key: PatternKey): { fam: Family; num: number } {
    const i = key.indexOf('-');
    return { fam: key.slice(0, i) as Family, num: Number(key.slice(i + 1)) };
}

/** 27 种牌面全表（按 万 → 条 → 筒 顺序，方便生成器切片） */
export const ALL_PATTERNS: PatternKey[] = (() => {
    const out: PatternKey[] = [];
    for (const f of FAMILIES) {
        for (let n = 1; n <= 9; n++) out.push(patternKey(f, n));
    }
    return out;
})();
