/**
 * ============================================================
 *  ★ S14.2c 立体装饰的"外扩量"（设计坐标单位）
 * ============================================================
 *  【为什么需要它 —— 一张立体牌画出来比它的盒子大】
 *  `TileRenderer.drawSolid` 画的三层里，只有「顶面」落在牌体盒子（CFG.TILE.W×H）
 *  以内，另两层都是**故意画到盒子外面**的：
 *    · 厚度壁：轮廓下移 DEPTH、右移 SIDE_DX
 *    · 投影  ：右下偏移 (SHADOW_DX, SHADOW_DY)，且每往外一层再扩 SHADOW_SPREAD
 *
 *  而 `Generator.resolvePositions` 的边界（limL/limR/limT/limB）原本只按
 *  **牌面体**算。于是在 S14.1 之后，贴边的牌会出现"牌面体在区内、侧壁和阴影
 *  探到区外"的情况 —— 表现是牌堆底部的侧壁压到暂存架、投影糊在暂存架标签上。
 *  这是"不报错、不崩、只是看起来不对"的那一类，只能靠算。
 *
 *  【怎么算】
 *  投影共 layers 层，第 i 层向外扩 `SHADOW_SPREAD × i`（i = 0..layers-1），
 *  所以最外层的额外量是 `SHADOW_SPREAD × (SHADOW_LAYERS - 1)`，记作 `sp`。
 *  四个方向各自取"厚度壁"与"投影"里更远的那个：
 *    DOWN  = max(DEPTH,      SHADOW_DY + sp)
 *    RIGHT = max(SIDE_DX,    SHADOW_DX + sp)
 *    LEFT  = max(0,          sp - SHADOW_DX)   ← 投影左边缘 = -sp + DX，DX ≥ sp 时为 0
 *    UP    = max(0,          sp - SHADOW_DY)
 *  实测（DEPTH 27 / sp 8 / DX 7 / DY 11）：DOWN 27、RIGHT 15、LEFT 1、UP 0。
 *  → **改动 SOLID 里任何一个数，这四个值都会跟着变**，边界自动跟上，不必两处对账。
 *
 *  ⚠️ 用法：这是**设计坐标**，进 resolvePositions 前必须 × (本关牌宽 / TILE_GEO.W)，
 *     和 DEPTH 的换算方式一致（见 Generator 里的 depthPx）。
 */
const _S = CFG.TILE.SOLID;
const _sp = _S.SHADOW_SPREAD * (_S.SHADOW_LAYERS - 1);
export const SOLID_OVERHANG = {
    UP: Math.max(0, _sp - _S.SHADOW_DY),
    DOWN: Math.max(_S.DEPTH, _S.SHADOW_DY + _sp),
    LEFT: Math.max(0, _sp - _S.SHADOW_DX),
    RIGHT: Math.max(_S.SIDE_DX, _S.SHADOW_DX + _sp),
};

/** 关卡配置的类型（供其它模块引用，避免各处重复声明） */
export interface LevelConfig {
    id: number;
    name: string;
    /** 牌总数（必须是 3a + 4b 的形式，见 LEVELS 上方说明） */
    tileCount: number;
    /**
     * 本关牌面的显示宽度（高度按 132:176 比例自动算）。**不填 = 用基准 `CFG.TILE.W`**。
     *
     * 只有 L1 例外：教学关保留绝对宽度 128（看得清、且要凑成整齐的 4×3=12 格）；
     * L2 起用 `tileScale: 1.25`（见下）在基准之上等比放大。
     * 用"可选 + 默认基准"而不是每关都写死，是为了将来调基准尺寸时
     * 不必回来同步四行数字（写死过一次，改基准时漏改了一行）。
     */
    tileW?: number;
    /**
     * 牌面尺寸相对基准 `CFG.TILE.W/H` 的**缩放倍数**（不填 = 1）。
     *
     * 【为什么要有它，而不是把 106 直接写进 tileW（2026-10-01 需求 #3）】
     * 用户口径：「把 L2-L4 牌的尺寸放大 1/4」—— 这是一条**相对**规则，
     * 不是三个绝对数字。写成 `tileScale: 1.25` 之后，日后若要调基准
     * （比如为了塞更多牌把基准从 85 降到 80），L2-L4 会自动跟着等比放大，
     * 不会出现"改了基准、漏改三行 tileW"的漂移；也一眼能看出
     * "这三关的牌是同一档大小"。
     *
     * 【1.25 落在哪个区间是安全的】
     * 放大后 106.25×142.5，格点阵列从 6×11=66 格变成 **5×8=40 格**。
     * 96 张要 40 格装下必须靠多层堆叠 —— 这正是本次一起改的"多层随机堆叠"
     * （见 STACK.FLOOR）。两者是同一次改动的两面：
     * **牌放大 → 格点变少 → 必须叠得更厚**，所以 #3 与 #4 只能一起做。
     *
     * ⚠️ 上限：牌宽 × 1.25 后若超过 `STACK.CELL_W × 1.25`，
     *    "同一行相邻牌不互相压"这条可读性底线会被破坏（见 STACK 段说明）。
     *    当前 106.25 < 116.25，余量 10px ✅。
     */
    tileScale?: number;
    /**
     * 牌堆里的牌是否**一律正立**（不参与四向随机朝向）。
     * 教学关（L1）必须为 true —— 新手第一次玩，牌面横着或倒着会直接劝退。
     * 不填 = false（L2 起四向随机：0 / 90 / 180 / 270）。
     */
    upright?: boolean;
    /**
     * **固定牌组**：写死的一副牌，不参与随机抽样。**按「组」写**，每组 3 张。
     *
     * 【为什么要有这个口子 —— 教学关的"必须"不能靠概率】
     * L1 的教学目标是"让玩家第一局就见到「吃」（顺子）"。
     * 而随机牌组做不到这件事：`patterns: 4` 只会在每族里取 1~2 个连号，
     * **凑不出 3 连号**，也就是说「吃」在教学关里物理上不可能发生 ——
     * 玩家第一关学到的只有「碰」，之后再见到「吃」会当成新机制重新学一遍。
     *
     * 写死牌组还顺带解决另外两件事：
     *   ① 可解性从"概率可解"变成"结构上必然可解"（牌组本身就是若干完整组），
     *      教学关不该有任何一次"运气不好打不过"；
     *   ② 通关路径唯一且清晰（见 L1 配置里的注释），便于验收与回归测试。
     *
     * 【为什么按组写、而不是写成一长串】
     * 因为这个"组"的划分后面还要用：`placeTiles` 会把**前 1/3 的牌**按组
     * 连续铺下去（见 `STACK.OPENING_EASY_RATIO`），让开局顺滑。
     * 如果这里只给一长串，那个环节就得回头猜"哪三张是一组"——
     * 而猜错的表现是"开局引导偶尔失灵"，最难查的一类问题。
     * 直接按组声明，信息就是完整的、不需要推断。
     */
    fixedBagGroups?: string[][];
    /** 关卡页展示用的层数（几何由 STACK 的格距决定，此值仅作难度语义与文案） */
    layers: number;
    /** 限时秒数，0 = 不限时 */
    timeLimit: number;
    /** 使用多少种牌面（3–9 为宜：太多则辨识困难，太少则太容易） */
    patterns: number;
    /**
     * 牌袋里**有几组是「吃」（顺子）**。不填 = 0（全部是「碰」组）。
     *
     * 【为什么要有这个参数（用户 2026-10-01：「从 L1 就要开始增加可以吃的组合」）】
     * 牌袋默认是"每种牌面各 3 张"，玩家一路碰到底就能通关 ——「吃」在这套结构里
     * 永远只是"可选操作"，玩家不会用、也就学不会。把牌袋的一部分改成连号组，
     * 「吃」就从"可选"变成"必须"，玩家会在反复使用中自然掌握。
     *
     * 取值建议：占全部组数的 1/4 左右（L2 3/12、L3 6/21、L4 9/32）。
     * 太少（1 组）玩家可能碰巧绕过去；太多（全部）时槽位会长期被"半组"占着，
     * 表面上更难，实际是让玩家在"等一张牌"里干等，那不是难度是运气。
     */
    chiGroups?: number;
    /** 是否启用「杠」（4 张相同） */
    gang: boolean;
    /** true = 平铺不叠压（教学关），false = 多层叠压 */
    flat: boolean;
    /** 教学提示语 */
    teach: string;
}
