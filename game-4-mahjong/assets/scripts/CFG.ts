        //  【用户要求的分工（原话）】
        //    "碰的效果是三张牌碰在一起，然后消除"  → 撞击（§十四）
        //    "连章是使用一个丝滑的动效来表示"      → 〔此处「连章」即「吃」〕
        //                                            流水汇合（本节）
        //
        //  【"流水汇合"为什么长这样】
        //  它与「碰」的撞击**处处互为反面**：
        //    · 碰：三张**同时**动     ／ 吃：三张**依次**汇入（错峰 70ms）
        //    · 碰：蓄力后退→猛冲(quadIn，越冲越快)　
        //      吃：**没有蓄力**，全程 sineInOut（首尾速度为零，起停都不见棱角）
        //    · 碰：挤压 + 冲击圆环 + 碎屑 + 牌堆上踢
        //      吃：**一个都不要**（这些元素本身就是"冲击"的语义）
        //    · 碰：停一拍 → 胀到 1.20 再缩到 0（"炸开"）
        //      吃：到齐后**轻微上浮 + 淡出**（"流走"，全程不缩放）
        //
        //  ★ 一句话总结：丝滑不是"加东西"，而是**减东西** ——
        //    把撞击那套元素全部拿掉、把时长拉长、把曲线换成首尾零速。
        // ----------------------------------------------------
        /** 三张依次汇入的错峰。比碰撞的接力错峰长，才看得清是"陆续汇入" */
