/**
 * ============================================================
 *  ★ S14.2c 立体装饰的"外扩量"（设计坐标单位）
 * ============================================================
 *  【为什么需要它 —— 一张立体牌画出来比它的盒子大】
 *  `TileRenderer.drawSolid` 画的三层里，只有「顶面」落在牌体盒子（CFG.TILE.W×H）
 *  以内，另两层都是**故意画到盒子外面**的：
 *    · 厚度壁：轮廓下移 DEPTH、右移 SIDE_DX
 *    · 投影  ：右下偏移 (SHADOW_DX, SHADOW_DY)，且每往外一层再扩 SHADOW_SPREAD
 *
 *  而 `Generator.resolvePositions` 的边界（limL/limR/limT/limB）原本只按
 *  **牌面体**算。于是在 S14.1 之后，贴边的牌会出现"牌面体在区内、侧壁和阴影
 *  探到区外"的情况 —— 表现是牌堆底部的侧壁压到暂存架、投影糊在暂存架标签上。
 *  这是"不报错、不崩、只是看起来不对"的那一类，只能靠算。
 *
 *  【怎么算】
 *  投影共 layers 层，第 i 层向外扩 `SHADOW_SPREAD × i`（i = 0..layers-1），
 *  所以最外层的额外量是 `SHADOW_SPREAD × (SHADOW_LAYERS - 1)`，记作 `sp`。
 *  四个方向各自取"厚度壁"与"投影"里更远的那个：
 *    DOWN  = max(DEPTH,      SHADOW_DY + sp)
 *    RIGHT = max(SIDE_DX,    SHADOW_DX + sp)
 *    LEFT  = max(0,          sp - SHADOW_DX)   ← 投影左边缘 = -sp + DX，DX ≥ sp 时为 0
 *    UP    = max(0,          sp - SHADOW_DY)
 *  实测（DEPTH 27 / sp 8 / DX 7 / DY 11）：DOWN 27、RIGHT 15、LEFT 1、UP 0。
 *  → **改动 SOLID 里任何一个数，这四个值都会跟着变**，边界自动跟上，不必两处对账。
 *
 *  ⚠️ 用法：这是**设计坐标**，进 resolvePositions 前必须 × (本关牌宽 / TILE_GEO.W)，
 *     和 DEPTH 的换算方式一致（见 Generator 里的 depthPx）。
 */
const _S = CFG.TILE.SOLID;
const _sp = _S.SHADOW_SPREAD * (_S.SHADOW_LAYERS - 1);
export const SOLID_OVERHANG = {
    UP: Math.max(0, _sp - _S.SHADOW_DY),
    DOWN: Math.max(_S.DEPTH, _S.SHADOW_DY + _sp),
    LEFT: Math.max(0, _sp - _S.SHADOW_DX),
    RIGHT: Math.max(_S.SIDE_DX, _S.SHADOW_DX + _sp),
};

/**
 * 立体装饰的设计基准宽 —— **必须等于 `TileData.TILE_GEO.W`（132）**。
 *
 * 【为什么不直接 import TileData.TILE_GEO】
 * CFG 是整个工程的"根"，TileData 反过来要读 CFG 的配色。这里 import 回去会
 * 形成环。所以只抄这一个数字，并在上面写死这行提醒 —— 它一旦和 TILE_GEO.W
 * 分家，所有"按牌宽缩放立体装饰"的地方都会静默偏掉（不报错、只是尺寸不对）。
 */
const SOLID_BASE_W = 132;

/**
 * 一张牌的**视觉**外接框：牌体 + 立体侧壁 + 投影。
 *
 * ------------------------------------------------------------
 *  【它解决什么问题】
 *  立体装饰**几乎全部长在牌体盒子之外**（向下 DEPTH、向右 SIDE_DX、右下投影）。
 *  所以"把牌摆在某块区域的正中"这件事，按**牌体**居中就是错的 ——
 *  牌会看起来整体偏下、偏小，而且底部那份厚度会捅出容器。
 *  关卡页卡片里的小牌首版正是这么摆的：牌体居中、厚度壁探出卡框 15px。
 *
 *  【口径】
 *  返回相对**牌体中心**的偏移与半宽半高（屏幕坐标，y 向上）：
 *    · dx / dy —— 视觉框中心相对牌体中心的偏移。想让牌"看上去摆正"，
 *                 就把节点放在 `目标中心 − (dx, dy)`。
 *    · hw / hh —— 视觉框的半宽半高（含立体装饰）。
 *
 *  ⚠️ 牌体高用 `TILE.H / TILE.W` 而不是 `TILE_GEO.H / TILE_GEO.W`：
 *     全工程算牌高的地方（`tileSizeOf`、`TileView`）都用前者，这里必须同源。
 *     两者差 0.6%（1.3412 vs 1.3333），混用会让"卡片里摆正了、牌堆里歪一点"。
 */
export function tileVisualBox(w: number): { dx: number; dy: number; hw: number; hh: number } {
    return rotatedVisualBox(w, w * (CFG.TILE.H / CFG.TILE.W), 0);
}

