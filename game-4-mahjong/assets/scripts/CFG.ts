        /**
         * 汇合后相邻两张的中心间距 = 槽格宽 × 这个比例。
         *   0   = 完全叠死（看不清牌面，也确认不了"汇成一处"的是哪三张）；
         *   1   = 等于没动。
         * 0.55 = "明显汇拢"与"仍能看出是三张不同的牌"之间的折中。
         * （碰是 0.45、叠得更狠 —— 因为它三张牌面完全相同，叠了不丢信息。）
         */
